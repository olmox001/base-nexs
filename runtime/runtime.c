__attribute__((weak)) int nexs_embed_load_all(EvalCtx *ctx) { (void)ctx; return 0; }

/* The embedded program is a boot image, NOT a second filesystem. Only
 * actual NXOLMO registry objects own the installed resource names.
 * Host-installed resources take priority; ENOENT/ENOSYS alone permit an
 * immutable linked LIBRARY image to materialize as a registry Value.
 * Example scripts never become automatic registry resources. */
static int nexs_bundle_name(const char *name, char path[REG_PATH_MAX]) {
  if (name == NULL || path == NULL)
    return -1;
  /* Source catalogs restrict roots; the ONE RegKey parser owns exact
   * component lengths, forbidden dot segments and full-path capacity. */
  /* Only installed runtime libraries/services are admitted at startup.
   * Example scripts stay on explicitly available external VFS mounts. */
  if (strncmp(name, "nxlib/", 6U) != 0)
    return -1;
  size_t length = 0U;
  while (length < REG_PATH_MAX - 1U && name[length] != '\0')
    ++length;
  if (length == 0U || length == REG_PATH_MAX - 1U ||
      name[length] != '\0')
    return -1;
  path[0] = '/';
  memcpy(path + 1U, name, length + 1U);
  return reg_path_valid(path) ? 0 : -1;
}

/* The bootstrap classifier is shared by hosted and compiler-generated
 * loaders. Only direct child .nx files under nxlib run at bootstrap, never a
 * service merely because its source file exists in the same namespace. */
int nexs_source_is_bootstrap_library(const char *logical, const char *source) {
  if (logical == NULL || source == NULL)
    return -1;
  if (strncmp(logical, "nxlib/", 6U) != 0 ||
      strchr(logical + 6U, '/') != NULL)
    return 0;
  char mapped[REG_PATH_MAX];
  if (nexs_bundle_name(logical, mapped) != 0)
    return -1;
  size_t index = 0U;
  while (index < MAX_STR_LEN) {
    const char ch = source[index];
    if (ch == '\0')
      return 0;
    if (ch == ' ' || ch == '\t' || ch == '\n' || ch == '\r') {
      ++index;
    } else if (ch == '#') {
      while (index < MAX_STR_LEN && source[index] != '\0' &&
             source[index] != '\n')
        ++index;
    } else {
      return strncmp(source + index, "library", 7U) == 0 &&
             (source[index + 7U] == ' ' ||
              source[index + 7U] == '\t');
    }
  }
  return -1;
}

/* Exactly one registry object owns an installed or embedded logical source.
 * Existing admitted resources always win; no shadow mount/sentinel data. */
int nexs_runtime_install_source(const char *logical, const char *source) {
  char mapped[REG_PATH_MAX];
  if (source == NULL || nexs_bundle_name(logical, mapped) != 0)
    return -1;
  if (reg_lookup(mapped) != NULL)
    return 0;
  Value value = val_str(source);
  if (value.type != TYPE_STR) {
    val_free(&value);
    return -1;
  }
  int status = reg_set(mapped, value, RK_READ);
  val_free(&value);
  return status;
}

static int nexs_bundle_resource_admissible(const char *logical) {
  char mapped[REG_PATH_MAX];
  const char *host = nexs_platform_source_path(
      logical, mapped, sizeof(mapped));
  if (host == NULL)
    return -1;
  FILE *installed = fopen(host, "rb");
  if (installed != NULL) {
    int closed = fclose(installed);
    return closed == 0 ? 0 : -1;
  }
  nx_status status = nexs_source_status_from_errno(errno);
  return nexs_source_embedded_admissible(status) ? 1 : -1;
}

static int nexs_runtime_publish_embedded_sources(void) {
  size_t count = nexs_embedded_resource_count();
  if (count > 4096U)
    return -1;
  /* Check the *entire* image before publishing the first registry node. */
  for (size_t i = 0U; i < count; ++i) {
    const char *name = nexs_embedded_resource_at(i);
    /* Explicit AOT example dependencies are not startup resources. */
    if (name != NULL && strncmp(name, "example/", 8U) == 0)
      continue;
    char path[REG_PATH_MAX];
    if (nexs_bundle_name(name, path) != 0 ||
        nexs_embedded_lookup(name, NULL) == NULL)
      return -1;
  }
  for (size_t i = 0U; i < count; ++i) {
    const char *name = nexs_embedded_resource_at(i);
    if (name != NULL && strncmp(name, "example/", 8U) == 0)
      continue;
    char path[REG_PATH_MAX];
    if (nexs_bundle_name(name, path) != 0)
      return -1;
    if (reg_lookup(path) != NULL)
      continue;
    int admitted = nexs_bundle_resource_admissible(name);
    if (admitted < 0)
      return -1;
    if (admitted == 0)
      continue;
    if (nexs_runtime_install_source(name,
                                    nexs_embedded_lookup(name, NULL)) != 0)
      return -1;
  }
  return 0;
}

/* =========================================================
   RUNTIME INIT
   ========================================================= */

int nexs_runtime_init(void) {
  /* Never zero the live allocator underneath existing registry Values.
   * A future RuntimeInstance owns independent domains; this singleton
   * entry point must reject reentry BEFORE touching any live memory. */
  if (g_registry.root != NULL || g_registry.total_keys != 0U)
    return -1;
  /* 1. Clear buddy pool and tree */
  memset(memory_pool, 0, POOL_SIZE);
  memset(buddy_tree, 0, sizeof(buddy_tree));

  /* 2. Install registry-owned callable Value lifetime operations */
  fn_value_hooks_init();

  /* 3. Initialise hierarchical registry */
  if (reg_init() != 0)
    return -1;

  /* 4. Initialise fd table (stdin/stdout/stderr) */
  if (sysio_init() != 0)
    return -1;

  /* 5. Register standard built-ins */
  builtins_register_all();
  nexs_textbuf_register();

  /* 6. Register Plan 9 I/O built-ins */
  sysio_register_builtins();

  /* 7. Register Plan 9 process built-ins */
  sysproc_register_builtins();

  /* 8. Register HAL module builtins */
  if (hal_module_register_builtins() != NX_STATUS_OK)
    return -1;

  /* 9. Register native platform capabilities, when provided. */
  nexs_platform_register();

  /* 10. Initialise the selected HAL driver. */
  nexs_hal_init();

  /* 11. Admit image sources into the SAME registry namespace before
   * source execution. No shadow /sys/vfs/files or synthetic VFS. */
  if (nexs_runtime_publish_embedded_sources() != 0)
    return -1;

  /* 12. Load embedded dependencies (if any) */
  EvalCtx ctx_emb;
  eval_ctx_init(&ctx_emb);
  if (nexs_embed_load_all(&ctx_emb) != 0)
    return -1;
  return 0;
}

int nexs_runtime_autoload(void) {
  return nexs_platform_autoload();
}
