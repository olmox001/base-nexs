/* Optional platform bind step, after the builtin table is initialized.
 * OS1 uses explicit capability registration because its CRT need not execute
 * hosted constructor sections; other targets keep their existing drivers.
 */
/* Optional platform lifecycle hook: hosted and bare-metal are intentionally
 * no-op until a platform adapter overrides it. A weak *definition* is
 * required on Mach-O, where an unresolved weak ELF reference is not portable.
 */
__attribute__((weak)) void nexs_platform_register(void) {}

/* Hosted platforms and physical HAL retain original source-path semantics. */
__attribute__((weak)) const char *nexs_platform_source_path(
    const char *path, char *storage, size_t capacity) {
  (void)storage;
  (void)capacity;
  return path;
}

/* The host adapter overrides this without linking into OS1/guest images. */
__attribute__((weak)) void nexs_host_source_root_init(const char *executable) {
  (void)executable;
}

